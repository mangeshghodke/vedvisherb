/**
 * Seeds the Supabase products table from src/data/products.json.
 *
 *   node scripts/seed-products.mjs --dry-run     show planned changes, write nothing
 *   node scripts/seed-products.mjs                write directly (needs service_role key)
 *   node scripts/seed-products.mjs --sql          emit seed.sql to paste into SQL Editor
 *
 * Safe to re-run: existing rows are matched by name and updated, not duplicated.
 */
import fs from 'node:fs'
import path from 'node:path'
import { createClient } from '@supabase/supabase-js'

// --- load .env without extra dependencies -------------------------------
function loadEnv() {
  const file = '.env'
  if (!fs.existsSync(file)) return
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z_]+)\s*=\s*(.*)\s*$/)
    if (!m) continue
    const key = m[1]
    let value = m[2].trim()
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }
    if (!process.env[key]) process.env[key] = value
  }
}

loadEnv()

const url = process.env.VITE_SUPABASE_URL
const anonKey = process.env.VITE_SUPABASE_ANON_KEY
const serviceKey = process.env.VITE_SUPABASE_SERVICE_ROLE_KEY

const dryRun = process.argv.includes('--dry-run')
const wantSql = process.argv.includes('--sql')

if (!url || !anonKey) {
  console.error('Missing credentials. Create .env with:')
  console.error('  VITE_SUPABASE_URL=https://<ref>.supabase.co')
  console.error('  VITE_SUPABASE_ANON_KEY=<anon public key>')
  process.exit(1)
}

const catalog = JSON.parse(fs.readFileSync(path.resolve('src/data/products.json'), 'utf8'))

/** UI shape -> DB column shape. Must stay in sync with toRow() in src/data/supabase.js */
function toRow(p, sortOrder) {
  return {
    name: p.name ?? '',
    tagline: p.tagline ?? '',
    category: p.category ?? 'Uncategorised',
    price: Number(p.price) || 0,
    weight: p.weight ?? '',
    description: p.description ?? '',
    long_description: p.longDescription ?? p.description ?? '',
    how_to_use: p.howToUse ?? '',
    benefits: Array.isArray(p.benefits) ? p.benefits : [],
    ingredients: Array.isArray(p.ingredients) ? p.ingredients : [],
    image: p.image ?? '',
    rating: Number(p.rating) || 0,
    reviews: Number(p.reviews) || 0,
    sort_order: sortOrder,
    published: true,
  }
}

const q = (v) =>
  v === null || v === undefined
    ? 'null'
    : `'${String(v).replace(/'/g, "''")}'`

const arr = (list) => `array[${list.map(q).join(', ')}]::text[]`

/**
 * Build an idempotent insert that needs no extra unique constraint.
 *
 * Uses INSERT ... SELECT ... WHERE NOT EXISTS rather than ON CONFLICT, because
 * the products table only has a unique index on slug. Safe to run repeatedly.
 *
 * Every literal carries an explicit ::type cast. Postgres infers a VALUES
 * column's type from its literals, so an unquoted-looking '0' would come
 * through as text and break `p.sort_order = v.sort_order`. Typed column aliases
 * ("as v (name text, ...)") are NOT valid Postgres syntax, so the casts belong
 * on the literals instead.
 */
function buildSql(rows) {
  const cast = (v, type) => `${v}::${type}`
  const t = (v) => cast(q(v ?? ''), 'text')
  const n = (v, type) => cast(String(Number(v) || 0), type)
  const b = (v) => cast(v === false ? 'false' : 'true', 'boolean')

  const values = rows
    .map((r) => {
      const cols = [
        t(r.name),
        t(r.tagline),
        t(r.category),
        n(r.price, 'numeric'),
        t(r.weight),
        t(r.description),
        t(r.long_description),
        t(r.how_to_use),
        cast(arr(r.benefits), 'text[]'),
        cast(arr(r.ingredients), 'text[]'),
        t(r.image),
        n(r.rating, 'numeric'),
        n(r.reviews, 'integer'),
        n(r.sort_order, 'integer'),
        b(r.published),
      ].join(', ')
      return `    (${cols})`
    })
    .join(',\n')

  return `-- Seed for Vedvis Herb
-- Generated by: node scripts/seed-products.mjs --sql
--
-- Paste into Supabase -> SQL Editor -> Run. Safe to run more than once:
-- rows that already exist (same name + sort_order) are skipped, not duplicated.
--
-- Every literal is cast to its column type (e.g. 350::numeric) so Postgres
-- does not infer text and fail the sort_order comparison.
-- Images are stored as filenames and resolve from /images at runtime, so this
-- file stays small.

insert into public.products (
  name, tagline, category, price, weight, description, long_description,
  how_to_use, benefits, ingredients, image, rating, reviews,
  sort_order, published
)
select
  v.name, v.tagline, v.category, v.price, v.weight, v.description,
  v.long_description, v.how_to_use, v.benefits, v.ingredients, v.image,
  v.rating, v.reviews, v.sort_order, v.published
from (values
${values}
) as v (
  name, tagline, category, price, weight, description, long_description,
  how_to_use, benefits, ingredients, image, rating, reviews,
  sort_order, published
)
where not exists (
  select 1 from public.products p
  where p.name = v.name and p.sort_order = v.sort_order
);

-- Optional: makes future runs faster and guards against accidental dupes.
-- create unique index if not exists products_name_sort_uniq
--   on public.products (name, sort_order);
`
}

async function main() {
  console.log(`Reading ${catalog.length} products from src/data/products.json\n`)

  const supabase = createClient(url, serviceKey ?? anonKey)

  const { data: existing, error: readErr } = await supabase
    .from('products')
    .select('id, name, sort_order')

  if (readErr) {
    console.error('Could not read the products table:', readErr.message)
    console.error('Run supabase/schema.sql in the SQL Editor first.')
    process.exit(1)
  }

  // Products.json has two rows both named "Kumkumadi Facial Gel", so match on
  // name+sort_order rather than name alone, or a re-run would collapse them.
  const key = (r) => `${r.name}::${r.sort_order}`
  const existingByKey = new Map((existing ?? []).map((r) => [key(r), r]))

  const rows = catalog.map((p, i) => {
    const row = toRow(p, i)
    const match = existingByKey.get(key(row))
    return match ? { ...row, id: match.id, isUpdate: true } : { ...row, isUpdate: false }
  })

  const toInsert = rows.filter((r) => !r.isUpdate)
  const toUpdate = rows.filter((r) => r.isUpdate)

  console.log(`  ${toInsert.length} to insert`)
  console.log(`  ${toUpdate.length} to update\n`)

  if (dryRun) {
    console.log('Dry run — nothing written:')
    for (const r of rows) {
      console.log(
        `  ${r.isUpdate ? '~' : '+'} ${r.name}  (${r.category}, Rs.${r.price}, sort ${r.sort_order})`
      )
    }
    return
  }

  // Path A: emit SQL for the user to paste (no extra credentials needed).
  if (wantSql || !serviceKey) {
    const out = path.resolve('supabase/seed.sql')
    fs.writeFileSync(out, buildSql(catalog.map((p, i) => toRow(p, i))))
    console.log(`Wrote ${path.relative(process.cwd(), out)}`)
    console.log('\nThe anon key cannot insert (row-level security blocks it), so paste that')
    console.log('file into Supabase → SQL Editor → Run. It is safe to run twice.')
    return
  }

  // Path B: write directly using the service_role key.
  if (toInsert.length) {
    const { error } = await supabase.from('products').insert(toInsert)
    if (error) {
      console.error('Insert failed:', error.message)
      process.exit(1)
    }
    console.log(`Inserted ${toInsert.length}.`)
  }

  if (toUpdate.length) {
    const { error } = await supabase.from('products').upsert(toUpdate)
    if (error) {
      console.error('Update failed:', error.message)
      process.exit(1)
    }
    console.log(`Updated ${toUpdate.length}.`)
  }

  const { count } = await supabase
    .from('products')
    .select('*', { count: 'exact', head: true })
    .eq('published', true)
  console.log(`\nDone. ${count} published products in the database.`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})